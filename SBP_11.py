#a program to find the simple interest when the value of principle,rate of interest and time period is given
p=int(input("Enter the Principle amountinitial money borrowed or invested: "))
r=int(input("Enter the Rate of Interest(per year (in %)): "))
t=int(input("Enter the Time Period(in years): "))
si=((p*r*t)/100)
print("The Simple Interest is ",si)

